/// Canonical application operations generated by every game UI.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum SessionCommand {
    /// Selects keyboard response before the flight configuration is sealed.
    SetKeyboardControls {
        /// Complete device response selection.
        settings: crate::flight_input::KeyboardControlSettings,
    },
    /// Opens flight settings.
    OpenSetup {},
    /// Returns to Title.
    ReturnToTitle {},
    /// Seals the selected configuration.
    Prepare {},
    /// Returns from Briefing to Setup.
    CancelBriefing {},
    /// Starts the existing launch countdown.
    StartCountdown {},
    /// Cancels the launch countdown.
    CancelCountdown {},
    /// Pauses the current flight.
    Pause {},
    /// Explicitly resumes the retained flight.
    Resume {},
    /// Finalizes the active flight by pilot request.
    Abort {},
    /// Reuses the retained flight configuration.
    Retry {},
    /// Repeats preparation of the sealed configuration.
    RetryBriefing {},
    /// Opens replay of the finalized record.
    EnterReplay {},
    /// Leaves replay for its Rust-owned return target.
    LeaveReplay {},
    /// Opens the independent Title demonstration.
    EnterAttract {},
    /// Returns from the demonstration to Title.
    LeaveAttract {},
    /// Resolves one existing preset.
    SelectPreset {
        /// Named preset; Custom is not a selectable shortcut.
        preset: DifficultyPreset,
    },
    /// Selects the Information axis.
    SelectInformation {
        /// Existing information level.
        information: InformationLevel,
    },
    /// Selects the Assistance axis.
    SelectAssistance {
        /// Existing assistance level.
        assistance: AssistanceLevel,
    },
    /// Selects the Weather axis.
    SelectWeather {
        /// Existing weather class.
        weather: WeatherClass,
    },
    /// Changes one Custom information cue.
    SetCue {
        /// Existing cue.
        cue: HudCue,
        /// Requested visibility.
        visible: bool,
    },
}

/// Canonical operations on the retained record and its existing playback clock.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum RecordCommand {
    /// Validates an analysis cursor request without moving the playback clock.
    SeekAnalysis {
        /// Requested recorded time.
        time_seconds: f64,
    },
    /// Moves the existing playback clock.
    SeekReplay {
        /// Requested recorded time.
        time_seconds: f64,
    },
    /// Toggles the existing playback clock.
    ToggleReplayPlaying {},
    /// Selects the existing half, normal or double playback rate by stable code.
    SetReplayRate {
        /// Zero is half speed, one normal speed, two double speed.
        code: u32,
    },
}

/// Shared selection and execution failure with its original classified cause.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ApplicationError {
    /// The live frame driver retained its original input, clock or execution failure.
    Flight(super::FlightFrameError),
    /// The existing session rejected this phase transition.
    Session(GameSessionError),
    /// The existing settings resolver rejected the preset.
    Configuration(ConfigurationError),
    /// The software authority could not be constructed.
    Control(ActuatorError),
    /// The registered scenario or physical configuration could not be prepared.
    Preparation(HybridSessionPreparationError),
    /// The command is not a difficulty selection.
    NotSelection,
    /// A validated pilot intent could not be constructed for the existing demonstration.
    Input(birdman_game_core::TailControlError),
    /// A demonstration record query rejected invalid or empty finalized data.
    Record(birdman_game_core::FlightRecordQueryError),
}

/// Exact metadata returned after the existing configuration is sealed.
pub struct PreparedFlight {
    pub(super) keyboard_controls: crate::flight_input::KeyboardControlSettings,
    pub(super) aircraft: birdman_game_core::AircraftModel,
    /// Archive definition identity.
    pub record_identity: FlightRecordTailIdentityDocument,
    /// Sealed software controller.
    pub controller_profile: TailControlProfile,
    /// Sealed distance-scoring direction.
    pub course_axis: CourseAxis,
    /// Resolved authority mode.
    pub control_mode: ControlMode,
    contact_shape: AircraftContactShape<'static, 'static>,
}

impl PreparedFlight {
    pub(super) fn advance(
        &mut self,
        session: &mut GameSession<'static>,
        input: TailFlightTickInput,
    ) -> Result<SessionSnapshot, GameSessionError> {
        session.advance_tail_flight_tick_with_shape_provider(input, &mut self.contact_shape)
    }
}

/// Resolves the existing four Assistance choices identically for every adapter.
pub(crate) fn control_mode(assistance: AssistanceLevel) -> Result<ControlMode, ActuatorError> {
    match assistance {
        AssistanceLevel::Strong => Ok(ControlMode::Automatic),
        AssistanceLevel::Manual => Ok(ControlMode::Manual),
        AssistanceLevel::Assisted | AssistanceLevel::Light => {
            FbwAuthority::try_new(if assistance == AssistanceLevel::Assisted {
                0.5
            } else {
                0.2
            })
            .map(ControlMode::Shared)
        }
    }
}

/// Resolves a typed difficulty selection without changing the session or physical state.
pub(crate) fn resolve_difficulty(
    session: &GameSession<'_>,
    current: DifficultySettings,
    command: &SessionCommand,
    seed: u64,
) -> Result<DifficultySettings, ApplicationError> {
    if session.snapshot().phase() != SessionPhase::FlightSetup {
        return Err(ApplicationError::Session(
            GameSessionError::InvalidTransition,
        ));
    }
    let selected = match *command {
        SessionCommand::SelectPreset { preset } => {
            DifficultySettings::preset(preset).map_err(ApplicationError::Configuration)?
        }
        SessionCommand::SelectInformation { information } => current.with_information(information),
        SessionCommand::SelectAssistance { assistance } => current.with_assistance(assistance),
        SessionCommand::SelectWeather { weather } => current.with_weather(weather),
        SessionCommand::SetCue { cue, visible } => current.with_hud_cue(cue, visible),
        _ => return Err(ApplicationError::NotSelection),
    };
    HybridSessionPreparation::select_scenario(selected.weather(), seed)
        .map_err(ApplicationError::Preparation)?;
    control_mode(selected.assistance()).map_err(ApplicationError::Control)?;
    Ok(selected)
}

/// Seals the same model, weather, controller and metadata into the existing session owner.
pub(crate) fn prepare_flight(
    session: &mut GameSession<'static>,
    difficulty: DifficultySettings,
    maximum_ticks: u64,
    seed: u64,
) -> Result<PreparedFlight, ApplicationError> {
    let control_mode = control_mode(difficulty.assistance()).map_err(ApplicationError::Control)?;
    let preparation = HybridSessionPreparation::try_new_for_weather(
        control_mode,
        maximum_ticks,
        seed,
        difficulty.weather(),
    )
    .map_err(ApplicationError::Preparation)?;
    let controller_profile = preparation.controller_profile();
    let course_axis = preparation.course_axis();
    let (configuration, record_identity) = preparation.into_parts();
    let aircraft_definition = crate::registered_aircraft()
        .map_err(HybridSessionPreparationError::Aircraft)
        .map_err(ApplicationError::Preparation)?;
    let mut contact_points = Vec::new();
    contact_points
        .try_reserve_exact(aircraft_definition.contact_points().len())
        .map_err(|_| {
            ApplicationError::Preparation(HybridSessionPreparationError::AllocationFailed)
        })?;
    contact_points.resize(
        aircraft_definition.contact_points().len(),
        BodyPoint::origin(),
    );
    let mut contact_shape =
        AircraftContactShape::try_from_owned(aircraft_definition, contact_points).map_err(
            |error| {
                ApplicationError::Preparation(HybridSessionPreparationError::Aircraft(
                    birdman_game_content::AircraftDefinitionError::Shape(error),
                ))
            },
        )?;
    let configuration = configuration
        .with_contact_shape(&mut contact_shape)
        .map_err(HybridSessionPreparationError::Scenario)
        .map_err(ApplicationError::Preparation)?;
    let aircraft = configuration.aircraft();
    session
        .prepare_flight(configuration)
        .map_err(ApplicationError::Session)?;
    Ok(PreparedFlight {
        keyboard_controls: crate::flight_input::KeyboardControlSettings::default(),
        aircraft,
        record_identity,
        controller_profile,
        course_axis,
        control_mode,
        contact_shape,
    })
}
